/* Read-only catalog audit/download. No order, visitor, admin or backend mutation. */
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const ROOT=path.resolve(__dirname,'..');
const RAW=path.join(ROOT,'assets/images/raw');
const PRODUCTS=path.join(ROOT,'assets/images/products');
const ALLOWED_HOSTS=new Set(['drive.google.com','drive.usercontent.google.com','lh3.googleusercontent.com']);
function imageUrl(value){try{const url=new URL(String(value||''));return url.protocol==='https:'&&ALLOWED_HOSTS.has(url.hostname)?url.href:'';}catch{return '';}}
async function main(){
 const config={window:{}};vm.runInNewContext(fs.readFileSync(path.join(ROOT,'assets/config.js'),'utf8'),config);
 const endpoint=new URL(config.window.YASHBI_CONFIG.apiUrl);endpoint.searchParams.set('action','catalog-images');
 const response=await fetch(endpoint,{signal:AbortSignal.timeout(30000)});assertResponse(response);
 const data=await response.json();if(!data.ok||!Array.isArray(data.images))throw Error('Catalog image response invalid');
 fs.mkdirSync(RAW,{recursive:true});
 const audit={auditedAt:new Date().toISOString(),source:'Google Apps Script GET catalog-images',remoteProductCount:data.images.length,localSourcesFound:0,downloaded:[],missingLocal:[],images:data.images};
 const sources={};
 for(const item of data.images){
   const id=String(item.id).toUpperCase();if(!/^(GW|JP|SW|SP)-00[1-8]$/.test(id))continue;
   const source=imageUrl(item.image),alt=imageUrl(item.alt)||source;
   sources[id]={image:source,alt};
   if(item.colorImages&&typeof item.colorImages==='object')sources[id].colorImages=Object.fromEntries(Object.entries(item.colorImages).map(([color,url])=>[color,imageUrl(url)]).filter(([,url])=>url));
   const stem=id.toLowerCase();
   const exists=[PRODUCTS,RAW].some(dir=>['.webp','.png','.jpg','.jpeg'].some(ext=>fs.existsSync(path.join(dir,stem+ext))));
   if(exists){audit.localSourcesFound++;continue;}
   if(!source){audit.missingLocal.push(id);continue;}
   const imageResponse=await fetch(source,{signal:AbortSignal.timeout(30000)});assertResponse(imageResponse);
   const type=(imageResponse.headers.get('content-type')||'').split(';')[0];
   const extension={'image/png':'.png','image/webp':'.webp','image/jpeg':'.jpg'}[type];
   if(!extension)throw Error(`${id}: Drive did not return a supported image (${type})`);
   const image=Buffer.from(await imageResponse.arrayBuffer());if(image.length>25*1024*1024)throw Error(`${id}: source exceeds25MB`);
   fs.writeFileSync(path.join(RAW,stem+extension),image);audit.downloaded.push({id,file:stem+extension,source,bytes:image.length});
 }
 fs.writeFileSync(path.join(RAW,'drive-catalog.json'),JSON.stringify(audit,null,2)+'\n');
 fs.writeFileSync(path.join(ROOT,'assets/product-image-sources.js'),'/* Original Google Drive references; storefront fallbacks only. Generated by tools/sync-image-sources.cjs. */\nwindow.YASHBI_IMAGE_SOURCES = '+JSON.stringify(sources,null,2)+';\n');
 if(audit.missingLocal.length)throw Error(`Missing local and remote source: ${audit.missingLocal.join(', ')}`);
 console.log(JSON.stringify({remoteSKU:audit.remoteProductCount,alreadyLocal:audit.localSourcesFound,downloaded:audit.downloaded.length,missing:audit.missingLocal.length},null,2));
}
function assertResponse(response){if(!response.ok)throw Error(`HTTP${response.status} from catalog/image source`);}
main().catch(error=>{console.error(error.message);process.exitCode=1;});
